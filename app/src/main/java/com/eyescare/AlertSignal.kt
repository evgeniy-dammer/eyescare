package com.eyescare

/**
 * Чем предупреждать о слишком близкой дистанции — помимо самого баннера.
 *
 * Зачем выбор: вибрация незаметна, когда телефон лежит на столе, а звук неуместен в тишине класса
 * или офиса. Один зашитый вариант заведомо неверен для половины ситуаций.
 *
 * Относится к **полноэкранному баннеру**, который приложение рисует само. Когда разрешения на
 * оверлей нет и предупреждение приходит уведомлением, звуком и вибрацией управляет системный канал
 * уведомлений: параметры канала после создания принадлежат пользователю, и переопределять их из
 * приложения нельзя (пересоздание канала сбросило бы его собственные настройки).
 */
enum class AlertSignal {
    /** Только баннер — ни звука, ни вибрации. */
    SILENT,

    /** Вибрация (поведение до появления настройки — оно и остаётся по умолчанию). */
    VIBRATION,

    /** Звук уведомления. */
    SOUND,

    /** И то и другое — для шумного места, где вибрацию не почувствуешь, а звук потеряется. */
    BOTH;

    val vibrates: Boolean get() = this == VIBRATION || this == BOTH
    val plays: Boolean get() = this == SOUND || this == BOTH

    companion object {
        /** Значение по умолчанию: то, как приложение вело себя до появления настройки. */
        val DEFAULT = VIBRATION

        /**
         * Разбор сохранённого имени. Неизвестное или отсутствующее значение (испорченное
         * хранилище, откат на старую версию) даёт [DEFAULT], а не исключение при старте.
         */
        fun fromName(raw: String?): AlertSignal =
            entries.firstOrNull { it.name == raw } ?: DEFAULT
    }
}
