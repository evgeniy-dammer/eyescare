package com.eyecare

/**
 * Определяет, как часто анализировать кадры, ради экономии батареи (ТЗ, оптимизация энергопотребления).
 *
 * Идея: распознавание лица ML Kit — основная нагрузка. Когда пользователь на безопасной дистанции,
 * высокая частота не нужна — анализируем редко. В «зоне внимания» у порога (и когда лицо только что
 * потеряно) возвращаемся к частому анализу ради отзывчивости оверлея и плавного показа дистанции.
 *
 * Класс без Android/ML Kit-зависимостей и без часов (текущее время передаёт вызывающий) — легко тестируется.
 */
object FrameRateGovernor {

    /** ~10 кадров/с — около и за порогом (нужна отзывчивость). */
    const val ACTIVE_INTERVAL_MS = 100L

    /** ~2 кадра/с — на безопасной дистанции (экономим батарею). */
    const val RELAXED_INTERVAL_MS = 500L

    /** Лицо не найдено: умеренно, чтобы вовремя заметить возвращение лица, но не жечь батарею. */
    const val IDLE_INTERVAL_MS = 400L

    /** «Зона внимания» над порогом (см): в её пределах держим высокую частоту. */
    const val NEAR_MARGIN_CM = 15

    /**
     * Минимальный интервал между обрабатываемыми кадрами для текущего (сглаженного) расстояния.
     * @param distanceCm последнее известное расстояние или `null`, если лицо не найдено.
     */
    fun intervalMsFor(distanceCm: Float?, thresholdCm: Int): Long {
        if (distanceCm == null) return IDLE_INTERVAL_MS
        return if (distanceCm < thresholdCm + NEAR_MARGIN_CM) ACTIVE_INTERVAL_MS else RELAXED_INTERVAL_MS
    }
}
