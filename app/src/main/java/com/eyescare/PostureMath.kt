package com.eyescare

import kotlin.math.atan2

/**
 * Геометрия «text neck»: насколько голова наклонена вниз **относительно вертикали**, а не
 * относительно камеры.
 *
 * Почему одного угла от ML Kit мало: `headEulerAngleX` описывает поворот лица относительно КАМЕРЫ.
 * Если телефон лежит на столе экраном вверх, а человек смотрит на него сверху, камера видит лицо
 * фронтально (`headEulerAngleX ≈ 0`) — при том, что шея согнута почти на 90°. И наоборот: телефон
 * подняли к лицу, шея прямая, но угол лица относительно камеры может быть ненулевым. Поэтому к углу
 * лица нужно добавить наклон самого устройства, а его даёт вектор гравитации.
 */
object PostureMath {

    /**
     * Наклон устройства от вертикали в градусах по вектору гравитации в координатах устройства
     * (ось Y — вдоль корпуса вверх, ось Z — из экрана в сторону пользователя).
     *
     * `0°` — экран вертикален (телефон держат перед лицом), `90°` — телефон лежит экраном вверх,
     * отрицательные значения — верх корпуса наклонён к пользователю.
     */
    fun deviceTiltFromVerticalDeg(gravityY: Float, gravityZ: Float): Float =
        Math.toDegrees(atan2(-gravityZ.toDouble(), -gravityY.toDouble())).toFloat()

    /**
     * Наклон головы вниз от вертикали (сгибание шеи) в градусах: `0°` — взгляд горизонтален,
     * `90°` — человек смотрит прямо вниз. Отрицательные значения — взгляд поднят выше горизонта.
     *
     * Вывод формулы. При фронтальном лице ([headEulerXDeg] = 0) взгляд направлен противоположно
     * нормали экрана, то есть наклонён вниз ровно на [deviceTiltDeg]. Положительный
     * `headEulerAngleX` у ML Kit означает, что лицо смотрит ВВЕРХ относительно камеры, — значит,
     * он уменьшает наклон. Отсюда `flexion = deviceTilt − headEulerX`.
     *
     * Проверки на крайних случаях: телефон вертикально + лицо фронтально → 0°; телефон лежит
     * экраном вверх + лицо фронтально → 90°; телефон вертикально + лицо опущено на 20°
     * (`headEulerX = −20`) → 20°.
     */
    fun neckFlexionDeg(deviceTiltDeg: Float, headEulerXDeg: Float): Float = deviceTiltDeg - headEulerXDeg
}
